// Builds the public website pages from src/.
//
//   node scripts/build-pages.mjs
//
// Each file in src/pages/ starts with a meta comment:
//   <!--meta {"title": "...", "description": "..."} -->
// and holds the page body. The shared head, header (navigation) and footer
// come from src/partials/. Output goes to the repository root, e.g.
// src/pages/cards.html -> cards.html. Edit src/, then run this script.

import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const partial = (name) => readFileSync(join(root, 'src', 'partials', name + '.html'), 'utf8');
const head = partial('head'), header = partial('header'), footer = partial('footer');
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');

const pagesDir = join(root, 'src', 'pages');
const built = [];
for (const file of readdirSync(pagesDir).filter((f) => f.endsWith('.html')).sort()) {
  const src = readFileSync(join(pagesDir, file), 'utf8');
  const m = src.match(/^<!--meta\s+(\{[\s\S]*?\})\s*-->\s*/);
  if (!m) throw new Error(`${file}: missing <!--meta {...} --> header`);
  const meta = JSON.parse(m[1]);
  const page = file.replace(/\.html$/, '');
  const body = src.slice(m[0].length);
  // Mark the current page in the navigation.
  const nav = header.replace(new RegExp(`data-nav="${page}"`, 'g'), `data-nav="${page}" aria-current="page"`);
  const html =
    head.replace(/\{\{title\}\}/g, esc(meta.title)).replace(/\{\{description\}\}/g, esc(meta.description)).replace(/\{\{page\}\}/g, page)
      .replace('<!DOCTYPE html>\n', `<!DOCTYPE html>\n<!-- Generated by scripts/build-pages.mjs from src/pages/${file}. Edit the source, not this file. -->\n`) +
    nav + '\n' + body.trim() + '\n' + footer;
  writeFileSync(join(root, file), html);
  built.push(file);
}
console.log('Built ' + built.length + ' pages: ' + built.join(', '));
